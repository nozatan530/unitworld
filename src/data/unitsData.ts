export function buildMapLinks(): MapLink[] {
  const links: MapLink[] = [];
  const seen = new Set<string>();
  for (const u of RAW_UNITS) {
    if (!u.forms || !u.forms[0]) continue;
    for (const [srcId, exp] of u.forms[0]) {
      const key = `${srcId}->${u.id}`;
      if (!seen.has(key) && unitsById[srcId]) {
        seen.add(key);
        links.push({ id: key, source: srcId, target: u.id, op: exp > 0 ? 'mul' : 'div', label: exp > 0 ? '×' : '÷' });
      }
    }
  }
  for (const [src, tgt, op] of CONVERSIONS) {
    const key = `${src}->${tgt}`;
    if (!seen.has(key) && unitsById[src] && unitsById[tgt]) {
      seen.add(key);
      links.push({ id: key, source: src, target: tgt, op });
    }
  }
  return links;
}

export const MAP_LINKS = buildMapLinks();

// Find units sharing the exact same dimension
export function getSameDimensionUnits(u: UnitDefinition): UnitDefinition[] {
  if (u.kind === 'scale') return [];
  const key = getDimKey(getUnitDim(u));
  return RAW_UNITS.filter((v) => v.id !== u.id && v.kind !== 'scale' && getDimKey(getUnitDim(v)) === key);
}

// Find downstream units that use this unit as ingredient
export function getDescendants(u: UnitDefinition): UnitDefinition[] {
  return RAW_UNITS.filter(
    (v) => v.id !== u.id && v.forms && v.forms.some((f) => f.some(([id]) => id === u.id))
  );
}

// Find upstream units (ingredients)
export function getAncestors(u: UnitDefinition): Array<{ unit: UnitDefinition; exp: number }> {
  if (!u.forms || !u.forms[0]) return [];
  return u.forms[0]
    .map(([id, exp]) => ({ unit: unitsById[id], exp }))
    .filter((item) => item.unit !== undefined);
}

