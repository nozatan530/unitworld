RAW_UNITS.forEach(getUnitDim);

// SI換算の係数。forms をもたない非SI単位と、forms では係数が表せない単位だけ明示する
const FACTORS: Record<string, number> = {
  cal: 4.184, kcal: 4184, kWh: 3.6e6, eV: 1.602176634e-19, u: 1.66053907e-27,
  nm: 1e-9, um: 1e-6, mm: 1e-3, cm: 1e-2, km: 1e3, g: 1e-3, L: 1e-3, mL: 1e-6,
  min: 60, h: 3600, day: 86400, yr: 3.15576e7,
  atm: 101325, hPa: 100, mmHg: 133.322, pct: 1e-2, ppm: 1e-6, permil: 1e-3,
  mg_dL: 1e-2, kJ_mol: 1e3, au: 1.495978707e11, ly: 9.4607e15, pc: 3.0857e16,
};

export function getUnitFactor(u: UnitDefinition): number {
  if (u._factor !== undefined) return u._factor;
  let f = 1;
  if (FACTORS[u.id] !== undefined) f = FACTORS[u.id];
  else if (u.forms && u.forms[0] && !u.dim) {
    for (const [id, exp] of u.forms[0]) {
      const parent = unitsById[id];
      if (parent) f *= Math.pow(getUnitFactor(parent), exp);
    }
  }
  u._factor = f;
  return f;
}
RAW_UNITS.forEach(getUnitFactor);

export const sameFactor = (a: number, b: number) => Math.abs(Math.log10(a) - Math.log10(b)) < 1e-6;

// 錬成の「結果」になれる単位：基本単位か、組み立て方(forms)をもつ単位。
// °C・eV・atm のように換算だけで定義される単位は、かけ算・わり算では作れない
export const isCraftable = (u: UnitDefinition) => u.kind === 'base' || (!!u.forms && u.kind !== 'scale');

export function getDimKey(dim: Record<string, number>): string {
  return BASE_ORDER.map((k) => dim[k] || 0).join(',');
}

export const sup = (n: number) => (n === 1 ? '' : n === -1 ? '⁻¹' : n === 2 ? '²' : n === -2 ? '⁻²' : n === 3 ? '³' : n === -3 ? '⁻³' : `^${n}`);

export function formatDimSI(dim: Record<string, number>, lang: 'ja' | 'en' = 'ja'): string {
  const num: string[] = [];
  const den: string[] = [];
  for (const k of BASE_ORDER) {
    const e = dim[k] || 0;
    if (e > 0) num.push(k + sup(e));
    else if (e < 0) den.push(k + sup(-e));
  }
  if (!num.length && !den.length) return lang === 'ja' ? '1 (無次元)' : '1 (dimensionless)';
  let s = num.length ? num.join('·') : '1';
  if (den.length) {
    s += '/' + (den.length > 1 ? `(${den.join('·')})` : den[0]);
  }
  return s;
}

export function formatDimBrackets(dim: Record<string, number>): string {
  const parts: string[] = [];
  for (const k of BASE_ORDER) {
    const e = dim[k] || 0;
    if (e) parts.push(BASE_LETTER[k] + sup(e));
  }
  return parts.length ? `[${parts.join(' ')}]` : '';
}

