export function getUnitDim(u: UnitDefinition): Record<string, number> {
  if (u._dim) return u._dim;
  if (u.dim) {
    u._dim = { ...u.dim };
    return u._dim;
  }
  const d: Record<string, number> = {};
  if (u.forms && u.forms[0]) {
    for (const [id, exp] of u.forms[0]) {
      const parent = unitsById[id];
      if (parent) {
        const parentDim = getUnitDim(parent);
        for (const k in parentDim) {
          d[k] = (d[k] || 0) + parentDim[k] * exp;
          if (d[k] === 0) delete d[k];
        }
      }
    }
  }
  u._dim = d;
  return d;
}

